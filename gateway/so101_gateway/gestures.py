"""Жесты — движения из нескольких поз подряд.

Пресет в бэкенде — ОДНА поза: рука доезжает до неё и замирает. Для «домой»
этого достаточно, а «помахать» так не выглядит маханием: рука один раз
переставляется в поднятое положение и стоит.

Здесь описаны последовательности. Проигрывает их шлюз (`GatewayService`),
проводя каждую точку через тот же ограничитель скорости, что и ручные
команды. Ничего «быстрее обычного» жест сделать не может — это важно, потому
что жест запускает случайный прохожий одной кнопкой.

Позы АБСОЛЮТНЫЕ и в РАДИАНАХ — включая `gripper`. Наружу схват отдаётся
нормированным 0..1 (docs/api.md), но эти позы не приходят с провода: они
уходят прямо в `CommandLimiter.set_pose_rad`, который нормировки не знает.
Диапазон схвата в радианах: −0.17…1.75.

Ограничения из URDF, за которые нельзя выходить:

    shoulder_pan   ±1.92    wrist_flex    ±1.66
    shoulder_lift  ±1.75    wrist_roll    −2.74…+2.84
    elbow_flex     ±1.69    gripper       −0.17…+1.75

Значения ниже выбраны с запасом от этих границ: жест должен читаться
издалека, но не биться в упоры.
"""

from __future__ import annotations

from typing import Dict, List, Tuple

__all__ = ["GESTURES", "Waypoint", "Gesture", "gesture_names"]

#: Точка жеста: поза и сколько задержаться в ней после доезда, секунды.
Waypoint = Tuple[Dict[str, float], float]
Gesture = List[Waypoint]


#: Рука поднята «для приветствия»: схват на высоте 0.52 м прямо над столом,
#: с выносом 0.16 м. Вынос важен не меньше высоты — из позы «строго вверх»
#: (вылет 0.06 м) поворот основания почти не двигал бы схват, и мах был бы
#: незаметен. Отсюда схват проходит по дуге 13 см.
#:
#: Значения найдены перебором по FK из URDF, а не подобраны на глаз: первая
#: версия давала высоту 0.23 м, то есть рука не поднималась, а складывалась.
_WAVE_UP: Dict[str, float] = {
    "shoulder_pan": 0.0,
    "shoulder_lift": 0.0,
    "elbow_flex": -1.35,
    "wrist_flex": 0.0,
    "wrist_roll": 0.0,
    "gripper": 0.45,
}


def _wave_at(pan: float, wrist: float) -> Dict[str, float]:
    """Поднятая рука, отклонённая по основанию на ``pan``."""
    pose = dict(_WAVE_UP)
    pose["shoulder_pan"] = pan
    # Кисть слегка запаздывает за основанием — от этого мах перестаёт
    # выглядеть поворотом манипулятора и начинает походить на движение
    # ладонью. Знак противоположен: кисть «отстаёт».
    pose["wrist_flex"] = _WAVE_UP["wrist_flex"] + wrist
    return pose


#: Амплитуда маха по основанию. 0.40 рад — это ±23°, видно с нескольких метров.
_WAVE_SWING = 0.40
#: Встречное отклонение кисти, придаёт движению живость.
_WAVE_LAG = 0.18


